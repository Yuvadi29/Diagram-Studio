-- ─────────────────────────────────────────────────────────────────────────────
-- RPC: atomic project creation and duplication (SECURITY INVOKER → RLS applies)
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function public.create_project(p_title text default 'Untitled diagram', p_description text default null)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_project uuid;
  v_title text := coalesce(nullif(trim(p_title), ''), 'Untitled diagram');
begin
  if auth.uid() is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  insert into projects (user_id, title, description) values (auth.uid(), left(v_title, 120), p_description)
  returning id into v_project;
  insert into diagrams (project_id, user_id, title, diagram_dsl)
  values (
    v_project,
    auth.uid(),
    left(v_title, 120),
    jsonb_build_object('id', v_project::text, 'title', left(v_title, 120), 'type', 'architecture', 'layout', 'left-to-right',
                       'nodes', '[]'::jsonb, 'edges', '[]'::jsonb, 'groups', '[]'::jsonb, 'version', 1)
  );
  insert into presentations (project_id, user_id, title) values (v_project, auth.uid(), left(v_title, 120));
  return v_project;
end;
$$;

create or replace function public.duplicate_project(p_project_id uuid)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_src projects%rowtype;
  v_new uuid;
  v_pres record;
  v_new_pres uuid;
begin
  select * into v_src from projects where id = p_project_id;
  if not found then
    raise exception 'project not found' using errcode = 'P0002';
  end if;
  insert into projects (user_id, title, description, thumbnail_url)
  values (auth.uid(), left(v_src.title || ' (copy)', 120), v_src.description, v_src.thumbnail_url)
  returning id into v_new;

  insert into diagrams (project_id, user_id, title, diagram_type, diagram_dsl, excalidraw_data, version)
  select v_new, auth.uid(), left(title || ' (copy)', 120), diagram_type, diagram_dsl, excalidraw_data, 1
  from diagrams where project_id = p_project_id;

  for v_pres in select * from presentations where project_id = p_project_id loop
    insert into presentations (project_id, user_id, title, active_format, landscape_config, portrait_config)
    values (v_new, auth.uid(), v_pres.title, v_pres.active_format, v_pres.landscape_config, v_pres.portrait_config)
    returning id into v_new_pres;
    insert into scenes (presentation_id, title, description, order_index, scene_data)
    select v_new_pres, title, description, order_index, scene_data from scenes where presentation_id = v_pres.id;
  end loop;
  return v_new;
end;
$$;

-- Atomically replace all scenes of a presentation (used by the scene builder).
create or replace function public.replace_scenes(p_presentation_id uuid, p_scenes jsonb)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  if not exists (select 1 from presentations where id = p_presentation_id) then
    raise exception 'presentation not found' using errcode = 'P0002';
  end if;
  delete from scenes where presentation_id = p_presentation_id;
  insert into scenes (id, presentation_id, title, description, order_index, scene_data)
  select (s ->> 'id')::uuid, p_presentation_id, left(s ->> 'title', 120), s ->> 'description', (s ->> 'order')::int, s
  from jsonb_array_elements(p_scenes) as s;
  update presentations set updated_at = now() where id = p_presentation_id;
end;
$$;

-- Render worker: claim the oldest queued export (service role only).
create or replace function public.claim_export_job()
returns setof public.exports
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  update exports set status = 'rendering', started_at = now(), progress = 0
  where id = (
    select id from exports where status = 'queued' order by created_at for update skip locked limit 1
  )
  returning *;
end;
$$;

